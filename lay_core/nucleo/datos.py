PREFIJOS = ["", "", "", "lay ", "oye lay ", "lay por favor ", "por favor ", "oye ", "ley ", "hey lay "]
SUFIJOS = ["", "", "", " por favor", " porfa", " ahora", " ya", " rápido"]


def _sin_tildes(t: str) -> str:
    return t.translate(str.maketrans("áéíóúü", "aeiouu"))


def generar(n_por_intencion: int = 220, semilla: int = 7) -> list[tuple[str, str]]:
    rnd = random.Random(semilla)
    datos: list[tuple[str, str]] = []
    for intencion, plantillas in P.items():
        vistos = set()
        intentos = 0
        while len(vistos) < n_por_intencion and intentos < n_por_intencion * 20:
            intentos += 1
            t = rnd.choice(plantillas)
            for clave, valores in VOCAB.items():
                while "{" + clave + "}" in t:
                    t = t.replace("{" + clave + "}", rnd.choice(valores), 1)
            t = rnd.choice(PREFIJOS) + t + rnd.choice(SUFIJOS)
            if rnd.random() < 0.35:
                t = _sin_tildes(t)
            vistos.add(t.strip())
        datos += [(t, intencion) for t in vistos]
    rnd.shuffle(datos)
    return datos


